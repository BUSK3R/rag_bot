# 구어체 질문을 공문 용어로 정규화하는 재작성 프롬프트. 실측 근거: "청년끼고"라는
# 표현에서 2.4B 는 오판("불가능"), 8B 는 회피로 둘 다 실패했지만, 같은 질문을
# "공동창업"으로 바꿔 물으면 둘 다 정답을 냈다. 병목은 생성이 아니라 용어 매핑이다.
#
# 지시문("~하세요") 대신 퓨샷 예시로 쓴 이유: 2.4B 는 규칙 목록에 "'청년 끼고' →
# '청년과 공동창업'" 예시를 넣어 줘도 무시하고 "청년과 함께"로 뭉갰다. 소형 모델은
# 설명을 따르는 것보다 패턴을 이어 쓰는 일을 훨씬 잘한다.
